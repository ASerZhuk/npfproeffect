/** «ООО Маслозавод Пензенский» → «ООО «Маслозавод Пензенский»»; для перечня заказчиков через запятую — каждый отдельно. */
export function quoteCustomer(raw: string): string {
  return raw
    .split(', ')
    .map((part) => {
      const m = part.match(/^((?:ООО|ОАО|ЗАО|АО|ПАО)(?: НПП| НПО)?)\s+(.+)$/);
      if (!m) return part;
      const rest = m[2].replace(/\s*\(ДП АО НегасПензаПром\)/, '');
      return `${m[1]} «${rest}»`;
    })
    .join(', ');
}
